const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 8 * 1024 * 1024 } });

export const api = Router();

api.get('/health', (_req, res) => res.json({ data: { status: 'ok' } }));
api.get('/ready', asyncHandler(async (_req, res) => {
  const mongoose = await import('mongoose');
  const ready = mongoose.connection.readyState === 1;
  res.status(ready ? 200 : 503).json({ data: { status: ready ? 'ready' : 'not_ready' } });
}));
api.get('/openapi.json', (_req, res) => res.json(openApiSpec));

